"""
Build src/lib/unit-pack/fonts.ts: the hieroglyph font (a subset of public/fonts/noto-egyptian*.woff2 holding every
sign the Ancient Egypt Writing Unit uses) and Cinzel, both as base64, so the PDF builds in any serverless function
without file tracing. Re-run after adding signs to src/lib/unit-pack/content.ts:

    python scripts/dev/build-unit-pack-fonts.py
"""
import base64, io, os, pathlib, re, tempfile
from fontTools import merge, subset
from fontTools.ttLib import TTFont

ROOT = pathlib.Path(__file__).resolve().parents[2]
SOURCES = [
    "src/lib/unit-pack/content.ts",
    "src/lib/hieroglyph-translator.ts",
    "src/lib/content/uniliterals.ts",
]
cps = set()
for s in SOURCES:
    text = (ROOT / s).read_text(encoding="utf-8")
    cps |= {ord(c) for c in text if 0x13000 <= ord(c) <= 0x1345F}
    # \u{13xxx} escapes too
    cps |= {int(h, 16) for h in re.findall(r"\\u\{(13[0-9A-Fa-f]{3})\}", text)}

# The site splits Noto Sans Egyptian Hieroglyphs in two (the common signs, then the rest): merge them back.
with tempfile.TemporaryDirectory() as tmp:
    halves = []
    for i, name in enumerate(["noto-egyptian-core.woff2", "noto-egyptian.woff2"]):
        half = TTFont(ROOT / "public/fonts" / name)
        half.flavor = None
        for tag in ("GSUB", "GPOS"):  # no shaping needed: one code point, one sign
            if tag in half:
                del half[tag]
        path = os.path.join(tmp, f"half{i}.ttf")
        half.save(path)
        halves.append(path)
    font = merge.Merger().merge(halves)
opts = subset.Options()
opts.layout_features = []
opts.notdef_outline = True
sub = subset.Subsetter(opts)
sub.populate(unicodes=sorted(cps))
sub.subset(font)
buf = io.BytesIO()
font.save(buf)
glyph = buf.getvalue()
cmap = font.getBestCmap()
missing = [hex(c) for c in cps if c not in cmap]
if missing:
    raise SystemExit(f"missing from the Noto font: {missing}")

display = (ROOT / "src/app/cartouche-image/cinzel-600.ttf").read_bytes()

out = ROOT / "src/lib/unit-pack/fonts.ts"
out.write_text(
    "/* Generated by scripts/dev/build-unit-pack-fonts.py: do not edit. Noto Sans Egyptian Hieroglyphs (subset) and Cinzel 600, both SIL OFL. */\n"
    f"export const UNIT_GLYPH_FONT = \"{base64.b64encode(glyph).decode()}\";\n"
    f"export const UNIT_DISPLAY_FONT = \"{base64.b64encode(display).decode()}\";\n",
    encoding="utf-8",
)
print(f"{len(cps)} signs, glyph font {len(glyph)} bytes, display {len(display)} bytes -> {out}")
